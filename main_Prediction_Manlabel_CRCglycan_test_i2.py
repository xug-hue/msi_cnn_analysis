# 打开CSV数据文件
def load_data_csv(Data_DIR):
    my_table = dt.fread(Data_DIR, sep=",", header=False)  ## datatable格式读取文件
    data = my_table.to_numpy()  ## datatable格式转np数组，保存int数据
    print(data.shape)
    return data


# 数据要变成(参数数量, 1)的形状
def convertdatashape(data, num):
    return np.array([data[num]]).T


def generate_predict_result_csv(MODEL_FILE, RESULT_DIR, sampleNum, data):
    model = load_model(MODEL_FILE)
    print(model.summary())
    # pre_lists = pd.read_csv(PRE_DIR,sep=r",",header=None)
    pre_result_list = []
    pre_classResult_list = []
    for samplei in range(sampleNum):
        pre_data = np.array(convertdatashape(data, samplei))
        pre_result = model.predict(np.array([pre_data]))  # 0-1概率预测
        #  print(pre_result) [[9.9986470e-01 1.1371366e-04 2.1607673e-05]]
        pre_result_list.append(pre_result[0])
        pre_classResult_list.append([np.argmax(pre_result[0]) + 1])
        if samplei % 1000 == 0:
            print(samplei)

    # print(np.array(pre_result_list).shape)  #两个类的置信概率数组
    # print(np.array(pre_classResult_list).shape) #预测类数组

    pre_result_list = np.column_stack((np.array(pre_result_list), np.array(pre_classResult_list)))
    # print(np.array(pre_result_list).shape)    #合并后数组shape

    with open(RESULT_DIR, 'w', encoding='utf-8', newline="") as f:
        for samplei in range(len(pre_result_list)):
            csv_write = csv.writer(f)
            csv_write.writerow(pre_result_list[samplei])
    print("predict finish")


